    /**
     * 拉丁面：**生成物**（`LatinGlyphData`，32 网格、**位图宽 == 真 advance**）。
     *
     * ★ 手写的 5×8 表已于 2026-10-17 退役（§24.2 #21）：固定 5 列让 `i` 与 `m`
     *   同宽（真值 0.275em vs 0.926em），是"字距不匀"的根。生成物的位图宽取自
     *   真字体的 advance ⇒ `glyphAdvance()` 的 `位图宽 / unitsPerEm` 天然正确。
     *
     * @return array<int, list<string>> 码位 → 行位图
     */
    public static function latin(): array
    {
        return self::index(LatinGlyphData::GLYPHS);
    }

    /** @return array<int, list<string>> 码位 → 行位图 */
    public static function cjk(): array
    {
        // ★ 手写的 16 字模**优先**（`+` 的左操作数在键冲突时胜出），`CjkGlyphData`
        //   只补缺 —— 于是"补齐用到的汉字"不动既有字形，示例/应用的中文都能上屏。
        return self::index(self::CJK_GLYPHS + CjkGlyphData::GLYPHS);
    }

    /**
     * @param array<string, string> $table
     * @return array<int, list<string>>
     */
    private static function index(array $table): array
    {
        $glyphs = [];
        foreach ($table as $char => $rows) {
            $decoded = Utf8::decode((string) $char);
            if ($decoded === []) {
                continue;
            }
            $glyphs[$decoded[0][0]] = explode('/', $rows);
        }
        return $glyphs;
    }
