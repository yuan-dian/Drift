    /** @return array<int, list<string>> 码位 → 行位图 */
    public static function latin(): array
    {
        return self::index(self::LATIN_GLYPHS);
    }

    /** @return array<int, list<string>> 码位 → 行位图 */
    public static function cjk(): array
    {
        return self::index(self::CJK_GLYPHS);
    }

    /**
     * @param array<string, string> $table
     * @return array<int, list<string>>
     */
    private static function index(array $table): array
    {
        $glyphs = [];
        foreach ($table as $char => $rows) {
            $decoded = Utf8::decode((string) $char);
            if ($decoded === []) {
                continue;
            }
            $glyphs[$decoded[0][0]] = explode('/', $rows);
        }
        return $glyphs;
    }
