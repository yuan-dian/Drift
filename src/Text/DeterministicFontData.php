 * **位图宽 == 真 advance** ⇒ 步进天然正确，§24.2 #21）、CJK 16 行（`CjkGlyphData`）。
 * 手写的拉丁 5×8 表已于 2026-10-17 退役。
 *
 * CJK 字形取自 **Noto Sans SC（SIL OFL 1.1）**：手写那 16 个是 16px 直出，
 * `CjkGlyphData` 那批是 64px 渲染后按面积覆盖度降到 16×16（`tools/font-gen-glyphs.py`）。
