<?php
declare(strict_types=1);

namespace Drift\Text;

/**
 * 一次编辑动作**改到了什么**（`TextDraft` 每个动作的返回值）。
 *
 * ★ 三态而不是 `bool`：调用方对"文本变了"与"只有插入符/选区变了"的处理**不同** ——
 *   文本变了要通知外部（`onChanged`）、要判"值有没有改"；只挪插入符则只需重画。
 *   合成一个 `bool` 会让调用方被迫比较前后文本（字符串比较）来区分两件事，
 *   而那是把状态机的内部知识搬到外面。
 *
 * ★ 没有"变了但不知道变什么"这一档：`TextDraft` 的每个动作自己知道，
 *   分不清就是它没想清楚。
 *
 * @api
 */
enum TextChange
{
    /** 什么都没动（同位置移动 / 空选区删除 / 空文本全选）—— 调用方应**早退**，不重画不通知 */
    case None;

    /** 只有插入符或选区动了（文本没变）—— 要重画，**不**通知外部 */
    case Caret;

    /** 文本变了（插入符/选区必然跟着动）—— 重画 + 通知外部 */
    case Text;
}
