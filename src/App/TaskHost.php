<?php
declare(strict_types=1);

namespace Drift\App;

/**
 * 后台执行端口（§17.2）—— **把"别占 UI 线程"收进一个可替换的端口**。
 *
 * ★ **它是平台能力，不是 UI 能力**（§11.2）：端口的存在让"UI 代码零改动"成为
 *   结构事实 —— Store / 页面只调 `$src->fetchPage()`，换后端是**组合根一行**
 *   （§17.2.3 / §A.2.4）。
 *
 * ```
 *         ┌──────────────── UI 线程（唯一）────────────────┐
 *         │  pump() → EventLoop → 树操作 / 布局 / 绘制      │
 *         │        ▲                              │        │
 *         │        │ $onDone(结果)                 │ submit │
 *         └────────┼──────────────────────────────┼────────┘
 *                  │                              ▼
 *         ┌────────┴──────────── TaskHost（平台端口）────────┴────────┐
 *         │  后端 A：线程池 —— ⛔ 当前 tpc 下不可实现（§17.2.2）        │
 *         │  后端 B：同步三态（`SyncTaskHost`，M1–M3 默认，永远可用）    │
 *         └───────────────────────────────────────────────────────────┘
 * ```
 *
 * ★ **后端 A 为什么不可用**（2026-10-16 探针 K，`probes/RESULTS.md` §11）：AOT 生成的
 *   代码里类 / 对象 / 属性访问走 `php_request_cache`，而它**只在模块 RINIT 里被建**
 *   ⇒ 没跑过 RINIT 的 worker 线程上全是空指针解引用，**单个 worker 也 SIGSEGV**。
 *   ⇒ 后端 A 转为"**对 tpc 的能力请求**"挂起（§17.2.2 / §24.2 #1），
 *   端口契约**不变**，tpc 补上"每线程进入请求"的入口后即可接入。
 *
 * @api
 */
interface TaskHost
{
    /**
     * 提交一个后台任务。
     *
     * ★ **`$onDone` 在 UI 线程上被调用**（回贴之后）—— 所以回调里可以安全地
     *   `$this->rows = …` + `notifyChanged()`。这是后端之间的**共同契约**：
     *   无论后端在哪个线程跑 `run()`，回调一定回到 UI 线程（§17.2.3）。
     *
     * ★ `$onDone` 是闭包、`$job` 是类 —— 这不是双标（§O-03）：闭包**不跨线程**
     *   （它在回贴之后才被调），跨边界的那一半必须是类。
     *
     * @param callable(mixed): void $onDone 结果回贴回调（收 `Job::run()` 的返回值）
     *
     * @api
     */
    public function submit(Job $job, callable $onDone): void;
}
